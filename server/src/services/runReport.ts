import type { Run, RunOutcome } from '@api-sentinel/shared';

/**
 * Downloadable reports. The HTML is opened outside the app, and it contains
 * text produced by the API under test (assertion actual values, messages),
 * so every value is escaped. No scripts, no external resources.
 */

const ESCAPES: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

export function escapeHtml(value: string | number | null): string {
  return String(value ?? '').replace(/[&<>"']/g, (char) => ESCAPES[char] ?? char);
}

const COLORS: Record<RunOutcome, string> = {
  pass: '#047857',
  fail: '#b91c1c',
  error: '#b45309',
};

function badge(outcome: RunOutcome): string {
  return `<span class="badge" style="background:${COLORS[outcome]}">${outcome.toUpperCase()}</span>`;
}

export function renderRunHtml(run: Run): string {
  const rows = run.results
    .map((result) => {
      const assertions = result.assertions
        .map(
          (a) => `<tr>
  <td>${badge(a.outcome)}</td>
  <td>${escapeHtml(a.name)}<div class="muted">${escapeHtml(a.message)}</div></td>
  <td><code>${escapeHtml(a.expected)}</code></td>
  <td><code>${escapeHtml(a.actual)}</code></td>
</tr>`,
        )
        .join('\n');
      const status =
        result.status === null
          ? `${escapeHtml(result.errorCode)}: ${escapeHtml(result.errorMessage)}`
          : `${escapeHtml(result.status)} ${escapeHtml(result.statusText)} · ${escapeHtml(result.durationMs)} ms`;
      return `<section>
<h2>${badge(result.outcome)} ${escapeHtml(result.name)}</h2>
<p><code>${escapeHtml(result.method)} ${escapeHtml(result.url)}</code></p>
<p>${status}</p>
${
  result.assertions.length === 0
    ? '<p class="muted">No assertions.</p>'
    : `<table><thead><tr><th>Result</th><th>Check</th><th>Expected</th><th>Actual</th></tr></thead><tbody>
${assertions}
</tbody></table>`
}
</section>`;
    })
    .join('\n');

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Test run: ${escapeHtml(run.collectionName)}</title>
<style>
body{font:14px/1.5 system-ui,sans-serif;color:#0f172a;max-width:960px;margin:2rem auto;padding:0 1rem}
h1{font-size:1.4rem}h2{font-size:1rem;margin-bottom:.25rem}
section{border-top:1px solid #e2e8f0;padding:.75rem 0}
table{border-collapse:collapse;width:100%;font-size:13px}
th,td{text-align:left;vertical-align:top;padding:.25rem .5rem;border-bottom:1px solid #f1f5f9;word-break:break-word}
code{font:12px ui-monospace,monospace}
.badge{color:#fff;border-radius:4px;padding:1px 6px;font-size:11px;font-weight:600}
.muted{color:#64748b;font-size:12px}
</style>
</head>
<body>
<h1>Test run: ${escapeHtml(run.collectionName)}</h1>
<p>${escapeHtml(run.startedAt)} · ${escapeHtml(run.durationMs)} ms · Environment: ${escapeHtml(run.environmentName ?? 'none')}</p>
<p><strong>${run.passed} passed</strong>, ${run.failed} failed, ${run.errors} errors, ${run.total} total</p>
${rows}
<p class="muted">Generated by API Sentinel. Response bodies and secret values are not included.</p>
</body>
</html>
`;
}

export function renderRunJson(run: Run): string {
  return `${JSON.stringify({ generatedBy: 'API Sentinel', run }, null, 2)}\n`;
}

/** A safe file name: reports are named after user-controlled collection names. */
export function reportFileName(run: Run, extension: 'json' | 'html'): string {
  const slug =
    run.collectionName
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 60) || 'run';
  return `${slug}-${run.startedAt.slice(0, 19).replace(/[:T]/g, '-')}.${extension}`;
}
